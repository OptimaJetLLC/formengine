/**
 * Represents an address.
 */
export type Address = {
  /**
   * The first line of the address.
   */
  address?: string
  /**
   * The city of the address.
   */
  city?: string
  /**
   * The state of the address.
   */
  state?: string
  /**
   * The postal code of the address.
   */
  postalCode?: string
  /**
   * The country of the address.
   */
  country?: string
}
